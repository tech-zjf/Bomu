    @MainActor
    func testCancellingQueuedReplacementDrainsPreviousScanAndPublishesCommittedFiles() async throws {
        let directory = FileManager.default.temporaryDirectory.appending(path: UUID().uuidString)
        let first = directory.appending(path: "First")
        let second = directory.appending(path: "Second")
        try FileManager.default.createDirectory(at: first, withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: second, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        try Data("first committed file".utf8).write(to: first.appending(path: "first.mp4"))
        try Data("second committed file".utf8).write(to: second.appending(path: "second.mp4"))
        let store = try PlaybackHistoryStore(path: ":memory:")
        let gate = ScanCompletionGate()
        let model = MediaLibraryModel(store: store, thumbnailCache: nil,
            scanner: HeldCompletionScanner(store: store, gate: gate))
        model.addFolder(first)
        for _ in 0..<200 {
            if await gate.isWaiting, model.indexedCount == 1 { break }
            try await Task.sleep(for: .milliseconds(5))
        }
        let firstIsWaiting = await gate.isWaiting
        XCTAssertTrue(firstIsWaiting)
        XCTAssertEqual(model.indexedCount, 1)

        model.addFolder(second)
        model.cancelScan()
        XCTAssertTrue(model.isScanning, "Cancellation must still wait for owned producer cleanup")
        await gate.release()
        for _ in 0..<200 where model.isScanning {
            try await Task.sleep(for: .milliseconds(5))
        }
        XCTAssertFalse(model.isScanning, "A cancelled replacement must retire its own scan state")
        XCTAssertTrue(model.recentlyDiscoveredFiles.isEmpty)
        XCTAssertNil(model.errorMessage)
        XCTAssertEqual(model.items.map(\.displayName), ["first.mp4"],
                       "Cancelling the replacement must still publish the previous committed scan")
        let cancelledRoots = await gate.roots
        XCTAssertEqual(cancelledRoots, [first.path], "The cancelled pending scan must never start")

        model.addFolder(second)
        for _ in 0..<200 {
            if !model.isScanning && model.items.count == 2 { break }
            try await Task.sleep(for: .milliseconds(5))
        }
        XCTAssertFalse(model.isScanning)
        XCTAssertEqual(Set(model.items.map(\.displayName)), ["first.mp4", "second.mp4"])
        let restartedRoots = await gate.roots
        XCTAssertEqual(restartedRoots, [first.path, second.path])
        await model.shutdown()
    }

