    private struct ControlledIndexingScanner: MediaLibraryScanning {
        private let indexingPermit: AsyncStream<Void>
        private let permitContinuation: AsyncStream<Void>.Continuation

        init() {
            (indexingPermit, permitContinuation) = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
        }

        func allowIndexing() {
            permitContinuation.yield(())
            permitContinuation.finish()
        }

        func scan(folder root: URL, includingSubfolders: Bool) -> MediaLibraryScan {
            let candidates = (0..<7).map { index in
                let name = "film-\(index).mp4"
                return MediaLibraryCandidate(url: root.appending(path: name),
                                             displayName: name, relativePath: name)
            }
            let (events, continuation) = AsyncThrowingStream<MediaLibraryScanEvent, Error>.makeStream()
            let task = Task {
                do {
                    for candidate in candidates { continuation.yield(.discovered(candidate)) }
                    for await _ in indexingPermit { break }
                    try Task.checkCancellation()
                    for (index, candidate) in candidates.enumerated() {
                        continuation.yield(.indexed(candidate, mediaFileID: Int64(index + 1)))
                    }
                    continuation.yield(.completed(.init(discoveredCount: candidates.count,
                                                          indexedCount: candidates.count,
                                                          skippedCount: 0, reconciledDeletions: true)))
                    continuation.finish()
                } catch {
                    continuation.finish(throwing: error)
                }
            }
            continuation.onTermination = { _ in task.cancel() }
            return MediaLibraryScan(events: events, task: task)
        }
    }

    private actor ScanCompletionGate {
        private var continuation: CheckedContinuation<Void, Never>?
        private var isReleased = false
        private(set) var isWaiting = false
        private(set) var roots: [String] = []

        func record(_ root: String) -> Bool {
            roots.append(root)
            return roots.count == 1
        }

        func wait() async {
            isWaiting = true
            guard !isReleased else { return }
            await withCheckedContinuation { continuation = $0 }
        }

        func release() {
            isReleased = true
            continuation?.resume()
            continuation = nil
        }
    }

    private struct HeldCompletionScanner: MediaLibraryScanning {
        let store: PlaybackHistoryStore
        let gate: ScanCompletionGate

        func scan(folder root: URL, includingSubfolders: Bool) -> MediaLibraryScan {
            let (events, continuation) = AsyncThrowingStream<MediaLibraryScanEvent, Error>.makeStream()
            let task = Task {
                let holdsCompletion = await gate.record(root.path)
                let operation = MediaLibraryScanner(historyStore: store).scan(
                    folder: root, includingSubfolders: includingSubfolders)
                var failure: Error?
                do {
                    for try await event in operation.events { continuation.yield(event) }
                } catch { failure = error }
                await operation.cancelAndWait()
                // Hold producer completion independently of stream cancellation.
                if holdsCompletion { await gate.wait() }
                continuation.finish(throwing: failure)
            }
            continuation.onTermination = { _ in task.cancel() }
            return MediaLibraryScan(events: events, task: task)
        }
    }

    private actor ScanCallRecorder {
        private var recordedRoots: [String] = []

        func record(_ root: String) {
            recordedRoots.append(root)
        }

        func roots() -> [String] { recordedRoots }
    }

    private struct ImmediateRecordingScanner: MediaLibraryScanning {
        let recorder: ScanCallRecorder

        func scan(folder root: URL, includingSubfolders: Bool) -> MediaLibraryScan {
            let (events, continuation) = AsyncThrowingStream<MediaLibraryScanEvent, Error>.makeStream()
            let task = Task {
                await recorder.record(root.path)
                continuation.yield(.completed(.init(discoveredCount: 0, indexedCount: 0,
                                                       skippedCount: 0, reconciledDeletions: true)))
                continuation.finish()
            }
            continuation.onTermination = { _ in task.cancel() }
            return MediaLibraryScan(events: events, task: task)
        }
    }

